DROP TABLE IF EXISTS sales;
CREATE TABLE sales (
  sale_id          STRING        COMMENT 'เลขที่รายการขาย',
  sale_date        DATE          COMMENT 'วันที่ขาย',
  sale_datetime    TIMESTAMP     COMMENT 'วันและเวลาที่ขาย',
  store_id         STRING        COMMENT 'รหัสสาขา (เชื่อมกับ stores)',
  product_id       STRING        COMMENT 'รหัสสินค้า (เชื่อมกับ products)',
  customer_id      STRING        COMMENT 'รหัสลูกค้าสมาชิก (NULL = ไม่ใช่สมาชิก)',
  quantity         INT           COMMENT 'จำนวนชิ้น (ติดลบ = รับคืน)',
  unit_price       DECIMAL(10,2) COMMENT 'ราคาขายต่อชิ้น (หลังโปรโมชัน)',
  discount_amount  DECIMAL(10,2) COMMENT 'ส่วนลดท้ายบิล (NULL = ไม่ได้บันทึก)',
  net_amount       DECIMAL(12,2) COMMENT 'ยอดขายสุทธิ = quantity * unit_price - ส่วนลด',
  payment_method   STRING        COMMENT 'วิธีชำระเงิน'
) COMMENT 'รายการขาย 1 แถว = สินค้า 1 รายการในบิล';

